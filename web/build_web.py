"""Assemble the web calculator from the repository files.

- web/example-data.js : the synthetic cohort and its configuration, and the configuration of the
                        article (column names only), as a script
- web/index.html      : web-src/app.html (the calculator, without document wrapper) wrapped in a
                        full HTML document; this is the page that is published

Run after changing examples/ or configs/:  python web/build_web.py
"""
import json
from pathlib import Path

WEB = Path(__file__).resolve().parent
ROOT = WEB.parent

cfg = json.loads((ROOT / "configs" / "example_synthetic.json").read_text(encoding="utf-8"))
csv = (ROOT / "examples" / "synthetic_cohort.csv").read_text(encoding="utf-8")
article = json.loads((ROOT / "configs" / "colombian_centenarians_manuscript.json").read_text(encoding="utf-8"))
(WEB / "example-data.js").write_text(
    "// Generated by web/build_web.py from configs/example_synthetic.json and examples/synthetic_cohort.csv.\n"
    "// Simulated data: no real participant is represented.\n"
    f"window.CHLI_EXAMPLE = {{config: {json.dumps(cfg, ensure_ascii=False)}, csv: {json.dumps(csv)}}};\n"
    "// Configuration of the article (column names of the Colombian cohort; no participant data).\n"
    f"window.CHLI_ARTICLE_CONFIG = {json.dumps(article, ensure_ascii=False)};\n",
    encoding="utf-8")

app = (ROOT / "web-src" / "app.html").read_text(encoding="utf-8")
head_end = app.index("</style>") + len("</style>")
html = ("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
        "<style>[hidden]{display:none!important} body{margin:0} img{max-width:100%}</style>\n"
        + app[:head_end] + "\n</head>\n<body>\n" + app[head_end:] + "\n</body>\n</html>\n")
(WEB / "index.html").write_text(html, encoding="utf-8")
print("web/example-data.js and web/index.html written")
